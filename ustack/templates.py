"""Built-in group templates (ustack/data/templates) and the lab's own saved templates
(library/templates). A device is always a copy: editing it never changes the template."""

from __future__ import annotations

import json
import uuid
from dataclasses import dataclass
from pathlib import Path

from . import paths
from .model import DeviceSpec, now_iso


@dataclass
class TemplateInfo:
    id: str
    name: str
    family: str
    builtin: bool
    path: Path
    description: str = ""


def _read(path: Path, builtin: bool) -> TemplateInfo | None:
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except Exception:
        return None
    return TemplateInfo(data.get("template_id") or path.stem, data.get("name", path.stem), data.get("family", "custom"),
                        builtin, path, data.get("description", ""))


BUILTIN_ORDER = ("xu_tmd", "mak_tmd", "xia_graphene", "ju_rhombohedral")


def list_templates() -> list[TemplateInfo]:
    out: list[TemplateInfo] = []
    builtin = {p.stem: p for p in paths.builtin_templates_dir().glob("*.json")}
    for key in BUILTIN_ORDER + tuple(sorted(set(builtin) - set(BUILTIN_ORDER))):
        if key in builtin:
            info = _read(builtin[key], True)
            if info:
                out.append(info)
    for p in sorted(paths.user_templates_dir().glob("*.json")):
        info = _read(p, False)
        if info:
            out.append(info)
    return out


def load_template(info_or_path: TemplateInfo | Path | str) -> DeviceSpec:
    path = info_or_path.path if isinstance(info_or_path, TemplateInfo) else Path(info_or_path)
    if not Path(path).exists():  # a built-in id
        path = paths.builtin_templates_dir() / f"{info_or_path}.json"
    return DeviceSpec.load(path)


def new_device_from(template: DeviceSpec, name: str | None = None) -> DeviceSpec:
    spec = template.copy()
    spec.id = uuid.uuid4().hex[:12]
    spec.created = spec.modified = now_iso()
    spec.name = name or spec.name
    spec.stage2 = {}
    spec.validation = {}
    spec.history = [{"time": spec.created, "note": f"Created from template '{template.template_id or template.name}'"}]
    return spec


def save_as_template(spec: DeviceSpec, name: str) -> Path:
    """Save the stack as a lab template (images, traced outlines and Stage 2 data are dropped)."""
    tpl = spec.copy()
    tpl.name = name
    tpl.template_id = "user_" + paths.safe_name(name).lower()
    tpl.id = tpl.template_id
    tpl.stage2, tpl.validation, tpl.history = {}, {}, [{"time": now_iso(), "note": f"Saved as template from '{spec.name}'"}]
    for layer in tpl.layers:
        layer.image = None
        layer.outline = None
    path = paths.user_templates_dir() / f"{tpl.template_id}.json"
    tpl.save(path)
    return path


def _as_template(spec: DeviceSpec, note: str) -> DeviceSpec:
    tpl = spec.copy()
    tpl.stage2, tpl.validation, tpl.history = {}, {}, [{"time": now_iso(), "note": note}]
    for layer in tpl.layers:
        layer.image = None
        layer.outline = None
    return tpl


def update_template(info: TemplateInfo, spec: DeviceSpec) -> Path:
    """Write an edited stack back over a lab template (its id and file kept; images, traced outlines and
    Stage 2 data dropped). Built-in templates are generated by tools/make_builtin_templates.py and are not
    overwritten: save an edited built-in as a lab template (:func:`save_as_template`)."""
    if info.builtin:
        raise ValueError("Built-in templates are not overwritten; save the edit as a lab template")
    tpl = _as_template(spec, f"Template edited ('{spec.name}')")
    tpl.template_id = tpl.id = info.id
    tpl.save(info.path)
    return info.path


def delete_template(info: TemplateInfo) -> None:
    if info.builtin:
        raise ValueError("Built-in templates cannot be deleted")
    info.path.unlink(missing_ok=True)


def build_from_scratch(name: str, config, substrate: str, bottom_gate: str | None, device_layers: list[str],
                       top_gate: str | None, contact_scheme: str = "edge_1d", contact_metal: str | None = None,
                       bottom_hbn: bool = True, top_hbn: bool = True, cap_hbn: bool = False, family: str = "custom",
                       sd_style: str = "auto") -> DeviceSpec:
    """A stack from the four choices of the New device dialog — substrate, bottom gate, device
    layers (bottom → top, one entry per flake piece), top gate — plus the hBN dielectrics the user
    ticks and the contacts. No dimension is set: Configure (or the user) fills them. Materials are
    taken as given (never substituted); ``None`` / "" means "no such layer"."""
    from .model import CONTACT_SCHEMES, FAMILIES, Layer, MetalPart, Q
    from .validation import assign_roles
    spec = DeviceSpec(name=name or "New device", family=family if family in FAMILIES else "custom",
                      contact_scheme=contact_scheme if contact_scheme in CONTACT_SCHEMES else "edge_1d")
    spec.hall_bar.sd_style = sd_style
    used: set[str] = set()

    def uid(base: str) -> str:
        k, out = 1, base
        while out in used:
            k += 1
            out = f"{base}{k}"
        used.add(out)
        return out

    def add(base: str, label: str, material: str, function: str) -> Layer:
        layer = Layer(uid=uid(base), name=label, material=material, function=function)
        mat = config.material(material) if material else None
        if mat is not None and mat.category == "metal":
            layer.metal_parts = [MetalPart(c, Q()) for c in mat.components]
        spec.layers.append(layer)
        return layer

    def metal_or_2d(material: str) -> str:
        mat = config.material(material)
        return "" if mat is None else ("metal" if mat.category == "metal" else mat.display_name)

    sub = add("S0", "Substrate", substrate, "substrate")
    smat = config.material(substrate) if substrate else None
    if smat is not None and smat.sio2_thickness_nm:
        sub.thickness_nm = Q(float(smat.sio2_thickness_nm), "material")
    if bottom_gate:
        kind = metal_or_2d(bottom_gate)
        add("BG", ("Pre-patterned metal bottom gate" if kind == "metal" else f"{kind or bottom_gate} bottom gate"), bottom_gate, "bottom_gate")
    if bottom_hbn:
        add("BBN", "Bottom hBN", "hBN", "bottom_gate_dielectric" if bottom_gate else "encapsulation")
    if contact_scheme == "prepatterned_bottom" and contact_metal:
        add("CT", f"{config.material(contact_metal).display_name if config.material(contact_metal) else contact_metal} pre-patterned contacts",
            contact_metal, "hall_bar_contacts")
    for i, material in enumerate(device_layers, 1):
        mat = config.material(material)
        shown = mat.display_name if mat else material
        add("D", f"{shown} (piece {i})" if len(device_layers) > 1 else shown, material, "device_layer")
    if top_hbn:
        add("TBN", "Top hBN", "hBN", "top_gate_dielectric" if top_gate else "encapsulation")
    if top_gate:
        kind = metal_or_2d(top_gate)
        add("TG", ("Metal top gate" if kind == "metal" else f"{kind or top_gate} top gate"), top_gate, "top_gate")
        if cap_hbn and kind != "metal":
            add("CAP", "hBN cap", "hBN", "encapsulation")
    if contact_scheme != "prepatterned_bottom" and contact_metal:
        mat = config.material(contact_metal)
        add("CT", f"{mat.display_name if mat else contact_metal} contacts", contact_metal, "hall_bar_contacts")
    assign_roles(spec, config)
    spec.description = "Built from scratch in UStack."
    spec.history = [{"time": spec.created, "note": "Built from scratch"}]
    return spec
