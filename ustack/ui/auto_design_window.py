    # ------------------------------------------------------------------ run
    def _movable(self) -> set:
        out = set()
        for i in range(self.list.topLevelItemCount()):
            it = self.list.topLevelItem(i)
            if it.checkState(0) == Qt.CheckState.Checked:
                out.add(it.data(0, Qt.ItemDataRole.UserRole))
        return out

    def run(self) -> None:
        for _ in range(3):                              # the lab values it needs, asked all at once
            try:
                items = al.required_values(self.spec, self.config)
            except ValueError as exc:
                self.state.setText(str(exc))
                return
            if not items:
                break
            dlg = MissingValuesDialog(items, self, "Values needed", "The auto design needs these lab values (saved to config/).")
            if not dlg.exec():
                return
            apply_answers(self.config, dlg.answers())
        self.results.clear()
        self.cands = []
        self.apply_btn.setEnabled(False)
        self.run_btn.setEnabled(False)
        self.cancel_btn.setVisible(True)
        self.busy.set_busy(True)
        self.state.setText("Starting …")
        self.worker = _Worker(self.spec.copy(), self.config, self.flow, self._movable(), self.twist.isChecked(),
                              self.thorough.isChecked(), self.pairs.value() or None)
        self.worker.progressed.connect(lambda t, f: self.state.setText(f"{int(100 * f)} % · {t}"))
        self.worker.finished_ok.connect(self._done)
        self.worker.failed.connect(self._failed)
        self.worker.start()

    def cancel(self) -> None:
        """Abort (user, 2026-11-21): the window is free at once; the run stops within a moment in the background
        (``ustack.cancel``: the search and the generators check the request in their inner loops) and its result,
        if any, is dropped."""
        w = self.worker
        if w is None:
            return
        w.stop = True
        for sig in (w.progressed, w.finished_ok, w.failed):
            try:
                sig.disconnect()
            except TypeError:
                pass
        self._stopping.append(w)
        w.finished.connect(lambda w=w: self._stopping.remove(w) if w in self._stopping else None)
        self.worker = None
        self._stopped()
        self.state.setText("Aborted — nothing was changed.")

    def _stopped(self) -> None:
        self.run_btn.setEnabled(True)
        self.cancel_btn.setVisible(False)
        self.busy.set_busy(False)

    def _failed(self, text: str) -> None:
        self._stopped()
        self.state.setText(text)

    def _done(self, cands: list) -> None:
        self._stopped()
        self.cands = cands
        self.results.clear()
        for k, c in enumerate(cands, 1):
            it = QtWidgets.QTreeWidgetItem(self.results, [f"{k}. {c.summary()}"])
            it.setData(0, Qt.ItemDataRole.UserRole, k - 1)
        self.state.setText(f"{len(cands)} layout(s) found." if cands else "No layout found.")
        if cands:
            self.results.setCurrentItem(self.results.topLevelItem(0))
            self.apply_btn.setEnabled(True)

    # ------------------------------------------------------------------ preview / apply
    def _current(self) -> al.Candidate | None:
        it = self.results.currentItem()
        return self.cands[it.data(0, Qt.ItemDataRole.UserRole)] if it is not None and self.cands else None

    def _show_current(self) -> None:
        """Before a run: the flakes where they are now."""
        c = self.canvas
        c.clear_all()
        for z, layer in enumerate(self.spec.layers):
            if layer.outline:
                c.set_polygon(f"now:{layer.uid}", layer.outline, layer_color(layer, self.config), False, 100 + z, 0.10)
        c.fit()

    def preview(self) -> None:
        cand = self._current()
        if cand is None:
            return
        c = self.canvas
        c.clear_all()
        for z, layer in enumerate(self.spec.layers):
            poly = cand.outlines.get(layer.uid)
            if poly:
                c.set_polygon(f"cand:{layer.uid}", poly, layer_color(layer, self.config), False, 100 + z, 0.12)
        if cand.fingers:
            c.add_overlay_polys(cand.fingers, "#c0a060", 0.5, z=150, width=0.6)
        if cand.comb:
            c.add_overlay_polys(cand.comb, "#8a8f99", 0.5, z=151, width=0.6)
        for key, poly in cand.zones.items():
            c.add_overlay_polys([poly], "#202020", 0.15, z=152, width=1.2)
        c.fit()
        moved = ", ".join(self.spec.layer(u).label for u in cand.poses if self.spec.layer(u) is not None)
        self.detail.setText("  ".join(cand.notes) + (f"\nMoves: {moved}." if moved else "")
                            + ("\nRule errors: " + "; ".join(cand.errors[:4]) if cand.errors else "")
                            + ("\nFinger electrodes without a clear landing: " + ", ".join(cand.blocked) if cand.blocked else ""))

    def apply(self) -> None:
        cand = self._current()
        if cand is None:
            return
        moved = al.apply_candidate(self.win.spec, cand)
        self.win.layout_auto_applied(moved, cand)
        self.state.setText(f"Applied: {len(moved)} flake(s) moved (Undo reverts).")

    def closeEvent(self, e):  # noqa: N802 - Qt API
        if self.worker is not None and self.worker.isRunning():
            self.cancel()
        for w in list(self._stopping):
            w.wait(10000)
        super().closeEvent(e)
