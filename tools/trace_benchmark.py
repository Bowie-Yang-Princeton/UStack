"""Benchmark of the flake tracer on the lab's WSe2 batch-1 images (``WSe2 device training/Layer OM Image``).

For every target flake (``tools/trace_benchmark_seeds.json``) it compares the v0.3 wand (flood fill,
ΔE 12) with the current tracer:
  * stability — mean / worst IoU between the border from the reference click and from 8 other clicks
    inside the flake (the complaint was "not very stable, false edges");
  * auto pick — whether tracing without a click finds the same flake;
  * overlays (red = v0.3, green = current) for checking the borders by eye.
Writes docs/trace_benchmark.md and docs/training/trace_*.jpg.

    python tools/trace_benchmark.py
"""

from __future__ import annotations

import json
import sys
import time
from pathlib import Path

import cv2
import numpy as np

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from ustack import imaging  # noqa: E402

DATA = ROOT / "WSe2 device training" / "Layer OM Image"
OUT = ROOT / "docs" / "training"


def mask_of(poly, shape):
    m = np.zeros(shape[:2], np.uint8)
    cv2.fillPoly(m, [np.round(np.array(poly)).astype(np.int32)], 1)
    return m.astype(bool)


def iou(a, b):
    return (a & b).sum() / max(1, (a | b).sum())


def main() -> None:
    seeds = json.loads((ROOT / "tools" / "trace_benchmark_seeds.json").read_text(encoding="utf-8"))["images"]
    OUT.mkdir(parents=True, exist_ok=True)
    rng = np.random.default_rng(1)
    rows, sheet = [], []
    for e in seeds:
        img = imaging.load_image(DATA / e["file"])
        ctx = imaging.prepare_trace(img)
        new = lambda s: imaging.detect_flake(img, s, mode=e["mode"], context=ctx)  # noqa: E731
        old = lambda s: imaging.detect_flake(img, s, tolerance=12.0)  # noqa: E731
        vis = img.copy()
        lw = max(2, img.shape[1] // 500)
        for seed in e["seeds"]:
            r = {"file": e["file"], "seed": seed}
            t = time.time()
            ref_new = mask_of(new(seed), img.shape)
            r["t"] = time.time() - t
            try:
                ref_old = mask_of(old(seed), img.shape)
            except ValueError:
                ref_old = np.zeros(img.shape[:2], bool)
            er = cv2.erode(ref_new.astype(np.uint8), np.ones((25, 25), np.uint8)).astype(bool)
            ys, xs = np.nonzero(er)
            picks = rng.choice(len(xs), size=min(8, len(xs)), replace=False)
            for name, fn, ref in (("old", old, ref_old), ("new", new, ref_new)):
                vals = []
                for k in picks:
                    try:
                        vals.append(iou(mask_of(fn((xs[k], ys[k])), img.shape), ref))
                    except ValueError:
                        vals.append(0.0)
                r[name] = (float(np.mean(vals)), float(np.min(vals)))
            r["agree"] = iou(ref_old, ref_new)
            poly, _ = imaging.auto_trace(img, e["prefer"], e["mode"], ctx)
            r["auto"] = iou(mask_of(poly, img.shape), ref_new)
            rows.append(r)
            for m, col in ((ref_old, (0, 0, 255)), (ref_new, (0, 220, 0))):
                cnts, _ = cv2.findContours(m.astype(np.uint8), cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_NONE)
                cv2.drawContours(vis, cnts, -1, col, lw)
            cv2.circle(vis, tuple(int(v) for v in seed), lw * 4, (255, 255, 255), -1)
        small = cv2.resize(vis, (420, int(420 * vis.shape[0] / vis.shape[1])), interpolation=cv2.INTER_AREA)
        cv2.putText(small, Path(e["file"]).stem[:48], (6, 16), cv2.FONT_HERSHEY_SIMPLEX, 0.42, (255, 255, 255), 1)
        sheet.append(small)
    h = max(s.shape[0] for s in sheet)
    sheet = [cv2.copyMakeBorder(s, 0, h - s.shape[0], 0, 4, cv2.BORDER_CONSTANT, value=(255, 255, 255)) for s in sheet]
    while len(sheet) % 3:
        sheet.append(np.full_like(sheet[0], 255))
    grid = np.vstack([np.hstack(sheet[i:i + 3]) for i in range(0, len(sheet), 3)])
    cv2.imwrite(str(OUT / "trace_overlays.jpg"), grid, [cv2.IMWRITE_JPEG_QUALITY, 82])
    lines = ["# Flake tracer benchmark (WSe2 batch 1)", "",
             "Generated by `tools/trace_benchmark.py` from the lab's single-flake images in `WSe2 device training/Layer OM Image` "
             "(hBN, graphite and monolayer WSe2; two dark-field images). There are no hand-drawn reference borders, so the "
             "current tracer's borders were checked by eye on the overlays below; the numbers measure **stability**: the IoU "
             "between the border from the listed click and from 8 other clicks inside the same flake (mean / worst). "
             "*Auto* = IoU of the border found without any click with the clicked one. *Agree* = IoU between the two methods' "
             "borders from the same click.", "",
             "| Image | click (px) | v0.3 wand mean / worst | current mean / worst | agree | auto | time (s) |",
             "|---|---|---|---|---|---|---|"]
    for r in rows:
        lines.append(f"| {r['file']} | {r['seed'][0]}, {r['seed'][1]} | {r['old'][0]:.2f} / {r['old'][1]:.2f} | "
                     f"{r['new'][0]:.2f} / {r['new'][1]:.2f} | {r['agree']:.2f} | {r['auto']:.2f} | {r['t']:.2f} |")
    best: dict[str, float] = {}
    for r in rows:
        best[r["file"]] = max(best.get(r["file"], 0.0), r["auto"])
    auto_ok = sum(v > 0.9 for v in best.values())
    o = np.array([r["old"] for r in rows])
    n = np.array([r["new"] for r in rows])
    lines += ["", f"**Mean stability:** v0.3 {o[:, 0].mean():.2f} (worst click {o[:, 1].min():.2f}); current {n[:, 0].mean():.2f} "
              f"(worst click {n[:, 1].min():.2f}). **Auto pick:** the right flake on {auto_ok} of {len(seeds)} images without a click "
              "(on a flake cut into two pieces it finds one of them — 'Next candidate' gives the other).", "", "![overlays](training/trace_overlays.jpg)", "",
              "Red = v0.3 wand, green = current tracer, white dot = the click. The settings are `imaging.TRACE_DEFAULTS`."]
    (ROOT / "docs" / "trace_benchmark.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines[8:8 + len(rows)]))
    print(lines[-4])


if __name__ == "__main__":
    main()
